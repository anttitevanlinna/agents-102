#!/usr/bin/env node
// Builds the course fact sheet the home page relay grounds its answers in.
//
// Reads, never by hand:
//   curriculum/trainings/agents-101/<module>.md  Big Idea, exercises, skills, Key Concepts
//   curriculum/exercises/<exercise>.md            step headings
//   site/index.html  li[data-module] rows         time, what agents take, what you keep, what you end with
// Writes cloudflare/entry-worker/src/facts.js (FACTS text + STANDARD rows).
//
//   node scripts/build-entry-facts.js           write
//   node scripts/build-entry-facts.js --check   exit 1 if the file is stale

'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const TRAINING = path.join(ROOT, 'curriculum/trainings/agents-101');
const EXERCISES = path.join(ROOT, 'curriculum/exercises');
const HOME = path.join(ROOT, 'site/index.html');
const OUT = path.join(ROOT, 'cloudflare/entry-worker/src/facts.js');

// Terms a visitor has not met yet, said the way the page says them.
const PLAIN = [
  [/prompt injection/gi, 'a document that slips instructions to the agent'],
  [/Anything the agent reads can instruct it, a source included\./g, 'Anything the agent reads can carry instructions, a source document included.'],
  [/\bsubagents?\b/gi, 'helper agents'],
  [/\bgenerator\b/gi, 'writing agent'],
  [/\bfrontmatter\b/gi, 'header'],
];
const plain = s => PLAIN.reduce((t, [re, to]) => t.replace(re, to), s);

function section(md, name) {
  const lines = md.split('\n');
  const i = lines.findIndex(l => new RegExp('^## ' + name).test(l));
  if (i < 0) return [];
  const out = [];
  for (const l of lines.slice(i + 1)) { if (/^## /.test(l)) break; if (l.trim()) out.push(l.trim()); }
  return out;
}
const unmd = s => s.replace(/\*\*|`|\*/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').trim();
const attr = (tag, name) => { const m = tag.match(new RegExp(name + '="([^"]*)"')); return m ? m[1].replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"') : ''; };

function homeRows() {
  const html = fs.readFileSync(HOME, 'utf8');
  const rows = [...html.matchAll(/<li\b[^>]*data-module="[^"]+"[^>]*>/g)].map(m => m[0]);
  if (rows.length !== 7) throw new Error(`expected 7 li[data-module] rows in site/index.html, found ${rows.length}`);
  return rows.map(tag => ({
    page: attr(tag, 'data-module'), title: attr(tag, 'data-title'), min: Number(attr(tag, 'data-min')),
    agents: attr(tag, 'data-std-agents'), keep: attr(tag, 'data-keep'), end: attr(tag, 'data-std-end'),
  }));
}

function moduleFacts(row, n) {
  const md = fs.readFileSync(path.join(TRAINING, row.page + '.md'), 'utf8');
  const big = section(md, 'Big Idea').map(unmd).join(' ');
  const skills = section(md, "What You.ll Learn").filter(l => l.startsWith('- ')).map(l => unmd(l.slice(2)));
  const concepts = section(md, 'Key Concepts').filter(l => l.startsWith('- ')).map(l => unmd(l.slice(2)));
  const exercises = [...md.matchAll(/\[Exercise: ([^\]]+)\]\(exercises\/([^)]+)\.md\)/g)].map(([, name, file]) => {
    const ex = fs.readFileSync(path.join(EXERCISES, file + '.md'), 'utf8');
    const steps = [...ex.matchAll(/^## (.+)$/gm)].map(m => unmd(m[1]).replace(/^Phase \d+: /, ''));
    return steps.length ? `"${name}" (steps: ${steps.slice(0, 6).join('; ')})` : `"${name}"`;
  });
  return plain([
    `${n} ${row.title}, ${row.min} min.`,
    `Big idea: ${big}`,
    `Exercises: ${exercises.join(', ')}.`,
    `Skills: ${skills.join(', ')}.`,
    `Key points: ${concepts.join(' ')}`,
    `Agents take: ${row.agents} You keep: ${row.keep} You end with: ${row.end}.`,
  ].join('\n'));
}

function build() {
  const rows = homeRows();
  const facts = [
    'COURSE FACTS (from the Agents 101 module pages; use only these, invent no other course content)',
    '',
    'The learner names one challenge they carry at work that is not solved yet, not a task. Module 1 is about the learner themself. From Module 2 on, every module works on that same challenge. Each module hands the agents one more part of the job.',
    '',
    rows.map((r, i) => moduleFacts(r, i + 1)).join('\n\n'),
  ].join('\n');
  const standard = rows.map(r => ({ agents: r.agents, end: r.end }));
  return '// Generated by scripts/build-entry-facts.js from the module pages and site/index.html. Do not edit.\n' +
    'export const FACTS = ' + JSON.stringify(facts) + ';\n' +
    'export const STANDARD = ' + JSON.stringify(standard, null, 2) + ';\n';
}

const out = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== out) { console.error('cloudflare/entry-worker/src/facts.js is stale: run node scripts/build-entry-facts.js'); process.exit(1); }
  console.log('entry facts up to date');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log('wrote ' + path.relative(ROOT, OUT));
}
