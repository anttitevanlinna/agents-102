#!/usr/bin/env node
// instance-contract.js — the eval-instance record every per-file judge writes.
//
// One definition of the fields all classes share. Class templates used to
// carry their own copy of the JSON shape, and the copies drifted: story's said
// `"class": "storytelling"` while all 110 story instances say `story`; eight
// said `"file": "<absolute path>"` after the dispatcher required a repo-relative
// path; behavior's promised a `suggestions_count` no instance carries; none
// showed `body_sha`, `shape_hash`, `suggestions`, `na_reason` or `judge_owned`,
// which the dispatch preamble requires. A judge follows whichever copy it read.
//
// The brief (`derive-class-brief.js`) appends `render(cls)`; a judge without a
// brief prints it with this script. A class template names only the fields its
// class adds (CLASS_FIELDS below is the index of those, so the render can say
// what else to expect).
//
// Out of scope: cross_module (module-set record, one per set) and voice_panel
// (per-persona taste record). Their templates keep their own shapes.
//
// Usage: node curriculum/evals/scripts/instance-contract.js <class>
'use strict'
const { evalTrainings } = require('./scan-stale-classes.js')

const CLASSES = ['writing', 'story', 'technical', 'pedagogy', 'strategy', 'slides', 'behavior']
const ROW_VERDICTS = ['PASS', 'REVISE', 'N/A']
const VERDICTS = ['PASS', 'REVISE']

// What each class adds on top of the shared record, as its template defines it.
const CLASS_FIELDS = {
  writing: [],
  story: ['module_mood_contract', 'trace_status', 'mood_summary'],
  technical: ['platform_claims_checked', 'citations_checked', 'skills_referenced', 'urls_sampled'],
  pedagogy: [],
  strategy: ['strategy_doc_section_loaded'],
  slides: ['chunk_map', 'rules_evaluated[].chunks_flagged'],
  behavior: ['trace_status', 'prompts_evaluated', 'prompts_findings'],
}

function trainings() {
  return [...new Set(Object.values(evalTrainings()))].concat('shared')
}

function contract(cls) {
  if (!CLASSES.includes(cls)) throw new Error(`no per-file contract for class ${cls} (have: ${CLASSES.join(', ')})`)
  const rec = {
    class: cls,
    file: '<repo-relative path>',
    training: trainings().join(' | '),
    verdict: VERDICTS.join(' | '),
    body_sha: '<shasum -a 256 of the raw source, taken when you start reading>',
  }
  if (cls === 'behavior') return behavior(rec)
  rec.shape_hash = '<exactly as prefill-instance.js --write reports it>'
  rec.rules_evaluated = [{
    compendium: '<a real check_*.md filename, suffix included>',
    rule_index: '<the number as the compendium writes it: 17 | "9b" | 6.2; null only with judge_owned: true>',
    rule_lead: '<the bolded lead, verbatim>',
    verdict: ROW_VERDICTS.join(' | '),
    evidence: '<line:quote for REVISE and judgement PASS; the grep and its count for mechanical PASS; null for N/A>',
    na_reason: '<one clause, N/A rows only>',
    fix_hint: '<one line from this lens, not a recipe; null unless REVISE>',
    blocking: 'true | false',
  }]
  rec.suggestions = [{ rule: '<check_*.md §N>', line: '<int>', now: '<the sentence as it stands>', proposed: '<the sentence you would put there>' }]
  rec.blocking_findings_count = '<int: REVISE rows with blocking: true>'
  rec.nonblocking_findings_count = '<int: REVISE rows with blocking: false>'
  rec.notes = '<optional: cross-class observations, unverified mechanics>'
  return rec
}

// Behavior's ledger is prompts_findings (its template defines the rows). No
// behavior REVISE instance carries rules_evaluated, and the schema gate counts
// blocking findings from rules_evaluated whenever that array exists — so a
// behavior record never writes one.
function behavior(rec) {
  rec.verdict = 'PASS | REVISE | N/A (N/A only when the file has no prompt blocks)'
  rec.suggestions = [{ rule: '<pattern_id or check_*.md §N>', line: '<int>', now: '<the prompt line as it stands>', proposed: '<the line you would put there>' }]
  rec.blocking_findings_count = '<int: prompts_findings with verdict REVISE>'
  rec.nonblocking_findings_count = 0
  rec.notes = '<optional: judge-owned observations, cross-class notes, unverified mechanics>'
  return rec
}

function render(cls) {
  const extra = CLASS_FIELDS[cls]
  return [
    `## Output contract — ${cls}`,
    '',
    'Generated by `curriculum/evals/scripts/instance-contract.js`; this is the only',
    'copy of the shared fields. Write ONE JSON object with every field below, plus',
    extra.length
      ? `the fields your class template adds: ${extra.map(f => `\`${f}\``).join(', ')}.`
      : 'nothing else: your class template adds no fields.',
    'Values in angle brackets are descriptions, `a | b` is a choice; write real values.',
    cls === 'behavior'
      ? 'Your ledger is `prompts_findings`: write no `rules_evaluated` and no `shape_hash`; a judge-owned observation goes in `notes`.'
      : 'A judge-owned row (no numbered rule behind it) carries `"rule_index": null, "judge_owned": true`.',
    'Counts are derived from the rows, never authored separately: `check-instance-schema.js` fails a mismatch.',
    '',
    '```json',
    JSON.stringify(contract(cls), null, 2),
    '```',
    '',
  ].join('\n')
}

module.exports = { CLASSES, CLASS_FIELDS, VERDICTS, ROW_VERDICTS, contract, render, trainings }

if (require.main === module) {
  const cls = process.argv[2]
  try { process.stdout.write(render(cls)) } catch (e) { console.error(e.message); process.exit(1) }
}
